"""Fixed-template explanations of a Decision, in two views.

Never generated by the LLM, so they cannot be wrong in a way the gate was not.

public_view / render_public: the ONLY things handed to the LLM and the chat trace (the LLM
repeats what it is given, so anything here reaches the manager).
- No employee ids, no vmin / vmax, no size or hiding reason for hidden cells.
- L2 / L3 are not told apart: "hidden because everyone has the same value" or "hidden
  only to protect another cell" would leak what the hiding protects.
- L4.pairwise says "fewer than k people joined, left or had their data changed", never
  the split between membership (A) and value (B) changes or the exact count:
  "1 person's data changed" would itself tell a manager that someone just got a raise.
- An old release is named (label and date) only to the user who received it; a
  teammate's release is "an earlier answer given to your team".
  e.g. "Since your earlier question on Mon 11/09 ('Department=Sales, JobRole=Manager:
  avg MonthlyIncome'), fewer than 5 people in this group joined, left or had their data
  changed. Answering now would reveal their values."

audit_view / render_audit: ledger and reviewer. Exact rule, counts, releases and their
users. Neither view ever contains employee ids.
"""
from app.schemas import Decision

HIDING_RULES = ("L2.min_n", "L2.homogeneous", "L3.secondary")

PUBLIC_L1 = {
    "L1.identifier": "Employee identifiers cannot be used in a question or returned.",
    "L1.unlabelled": "These fields are not approved by the privacy policy yet: {fields}.",
    "L1.filter_field": "{fields} cannot be used to filter or group results. "
                       "Allowed: {allowed_fields}.",
    "L1.malformed": "A count takes no target field; sum and average need one.",
    "L1.role": "Your role ({role}) cannot ask for {what}.",
    "L1.extreme": "The maximum or minimum of {target} is never shown: it is one person's "
                  "exact value. An average by group, for example by JobLevel, can be "
                  "shown instead.",
}
GATE_ERROR = "This request could not be checked safely, so nothing was released."


def public_rule(decision: Decision) -> str | None:
    """Hide suppression reasons and historical timestamp ambiguity in public rule ids."""
    if decision.rule in HIDING_RULES:
        return "L2"
    if decision.rule == "L4.history":
        return "L4"
    return decision.rule


def public_view(decision: Decision, viewer: str | None = None) -> dict:
    """What the LLM and the trace may see. `viewer` = the user asking."""
    return {
        "status": decision.status,
        "rule": public_rule(decision),
        "evidence_text": render_public(decision, viewer),
        "cells": [{"key": c.key, "n": c.n, "value": c.value} for c in decision.cells],
        "hidden": [s["key"] for s in decision.suppressed],
        "allowed_transforms": list(decision.allowed_transforms),
    }


def audit_view(decision: Decision) -> dict:
    """What the ledger and the reviewer see."""
    return {
        "status": decision.status,
        "rule": decision.rule,
        "evidence_text": render_audit(decision),
        "evidence": decision.evidence,
        "suppressed": [{"cell_key": s["key"], "reason": s["reason"], "n": s["n"]}
                       for s in decision.suppressed],
        "allowed_transforms": list(decision.allowed_transforms),
    }


def render_public(decision: Decision, viewer: str | None = None) -> str | None:
    rule, ev = decision.rule, decision.evidence or {}
    if rule is None:
        return None
    if rule == "L4.history":
        return "This answer cannot be safely released alongside earlier answers."
    if rule in HIDING_RULES:
        keys = [s["key"] for s in decision.suppressed]
        if decision.status == "partial":
            return ("Some groups are hidden to protect individual privacy: "
                    f"{'; '.join(_key(k) for k in keys)}.")
        if keys == [{}]:
            return "This answer is hidden to protect individual privacy."
        return "Every group in this answer is hidden to protect individual privacy."
    if rule == "L4.pairwise":
        return (f"Since {_since(ev['old_release'], viewer)}, fewer than {ev['k']} people "
                "in this group joined, left or had their data changed. Answering now "
                "would reveal their values.")
    if rule == "L4.linear":
        return (f"Combined with {_sources(ev['terms'], viewer)}, this answer would let "
                "someone work out an individual employee's data.")
    if rule in PUBLIC_L1:
        what = f"{ev['metric']} of {ev['target']}" if ev.get("target") else ev.get("metric")
        return PUBLIC_L1[rule].format(
            fields=", ".join(ev.get("fields", [])),
            allowed_fields=", ".join(ev.get("allowed_fields", [])),
            role=ev.get("role"), target=ev.get("target"), what=what)
    return GATE_ERROR


def render_audit(decision: Decision) -> str | None:
    rule, ev = decision.rule, decision.evidence or {}
    if rule is None:
        return None
    if rule == "L4.history":
        return f"L4.history: historical value versions are ambiguous ({ev['reason']})."
    if rule in HIDING_RULES:
        return f"{rule}: hidden " + "; ".join(
            f"{_key(s['key'])}: {s['reason']} (n={s['n']})" for s in decision.suppressed)
    if rule == "L4.pairwise":
        old = ev["old_release"]
        return (f"L4.pairwise: cell {_key(ev['cell_key'])} vs {_release(old)}: "
                f"{ev['n_membership_changed']} joined/left, {ev['n_value_changed']} value "
                f"changes (k={ev['k']}).")
    if rule == "L4.linear":
        terms = " ".join(
            f"{t['coefficient']:+g} × "
            + (_release(t["release"]) if "release" in t
               else f"this answer {_key(t['this_answer'])}")
            for t in ev["terms"])
        return (f"L4.linear: {terms} isolates {ev['n_people']} employee(s), "
                f"{ev['n_value_changed']} of them by a value change.")
    if rule == "gate.error":
        return f"gate.error: {ev.get('error')}"
    return (f"{rule}: role={ev.get('role')}, metric={ev.get('metric')}, "
            f"target={ev.get('target')}, fields={ev.get('fields')}")


def _since(old: dict, viewer: str | None) -> str:
    if viewer is not None and old.get("user") == viewer:
        return f"your earlier question on {_day(old['created_at'])} ('{old['label']}')"
    return "an earlier answer given to your team"


def _sources(terms: list[dict], viewer: str | None) -> str:
    releases = [t["release"] for t in terms if "release" in t]
    own = [r for r in releases if viewer is not None and r.get("user") == viewer]
    parts = []
    if own:
        listed = "; ".join(f"'{r['label']}' on {_day(r['created_at'])}" for r in own)
        parts.append(f"your earlier answer{'s' if len(own) > 1 else ''} ({listed})")
    if len(own) < len(releases):
        parts.append("earlier answers given to your team")
    return " and ".join(parts) or "earlier answers"


def _release(old: dict) -> str:
    return (f"'{old['label']}' ({old.get('user') or 'unknown user'}, "
            f"{old['created_at']:%Y-%m-%d %H:%M}, n={old['n']})")


def _day(when) -> str:
    return when.strftime("%a %m/%d")


def _key(key: dict) -> str:
    return ", ".join(f"{k}={v}" for k, v in key.items()) or "(all)"
